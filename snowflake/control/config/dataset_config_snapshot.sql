CREATE TABLE IF NOT EXISTS PLATFORM_CONTROL.CONFIG.DATASET_CONFIG_SNAPSHOT (
    PROJECT_CODE VARCHAR NOT NULL,
    ENVIRONMENT VARCHAR NOT NULL,
    DATASET_ID VARCHAR NOT NULL,
    CONFIG_SCHEMA_VERSION NUMBER(38, 0) NOT NULL,
    GIT_SHA VARCHAR NOT NULL,
    CONFIG_HASH VARCHAR NOT NULL,
    CONFIG VARIANT NOT NULL,
    DEPLOYED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    DEPLOYED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CONSTRAINT PK_DATASET_CONFIG_SNAPSHOT PRIMARY KEY (
        PROJECT_CODE,
        ENVIRONMENT,
        DATASET_ID,
        GIT_SHA
    )
)
COMMENT = 'Immutable audit snapshots of validated Git-owned dataset configuration. Standard-table PK is declarative metadata, not a concurrency lock.';
