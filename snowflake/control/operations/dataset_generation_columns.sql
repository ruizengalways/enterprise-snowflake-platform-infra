    ADD COLUMN IF NOT EXISTS GENERATION NUMBER(38, 0) NOT NULL DEFAULT 1;

ALTER TABLE PLATFORM_CONTROL.OPERATIONS.PIPELINE_RUN
    ADD COLUMN IF NOT EXISTS GENERATION NUMBER(38, 0) NOT NULL DEFAULT 1;

ALTER TABLE PLATFORM_CONTROL.OPERATIONS.PIPELINE_CHECK_RESULT
    ADD COLUMN IF NOT EXISTS GENERATION NUMBER(38, 0) NOT NULL DEFAULT 1;

ALTER TABLE PLATFORM_CONTROL.OPERATIONS.PIPELINE_BOOTSTRAP
    ADD COLUMN IF NOT EXISTS GENERATION NUMBER(38, 0) NOT NULL DEFAULT 1;
